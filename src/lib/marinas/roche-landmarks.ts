export function rocheClearings(chart: ChartData) {
  return [
    ...Object.values(ROCHE_LANDMARKS).map((p) => {
      const [x, z] = geoToChart(chart, p.lat, p.lon);
      return { x, z, radius: p.radius };
    }),
    ...ROCHE_COTTAGES.map(([lat, lon, w, l]) => {
      const [x, z] = geoToChart(chart, lat, lon);
      return { x, z, radius: Math.hypot(w, l) / 2 + 3 };
    }),
  ];
}
